        <!-- Theme Initialization (Prevents FOUT/Theme Flash) -->
        <script>
            (function() {
                try {
                    const mode = localStorage.getItem('theme_mode') || localStorage.getItem('theme');
                    const isDark = mode === 'dark' || (!mode && window.matchMedia('(prefers-color-scheme: dark)').matches);
                    if (isDark) {
                        document.documentElement.classList.add('dark');
                    } else {
                        document.documentElement.classList.remove('dark');
                    }
                    const preset = localStorage.getItem('theme_preset');
                    if (preset && preset !== 'default') {
                        document.documentElement.setAttribute('data-theme', preset);
                    }
                } catch (e) {}
            })();
        </script>

        <!-- Fonts -->
        <link rel="preconnect" href="https://fonts.googleapis.com">
